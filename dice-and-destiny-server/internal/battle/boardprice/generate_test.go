// defaultBoardEnv rewrites the shipped default board from Generate.
const defaultBoardEnv = "BOARDPRICE_WRITE_DEFAULT_BOARD"

// The custom adventurer's shipped default board is exactly what Generate
// makes of the Lean template on the standard die at default picks.
func TestDefaultBoardIsGenerated(t *testing.T) {
	b := testBuilder(t)
	choice, report, err := b.Price(b.Default("lean", "standard_d6"))
	if err != nil {
		t.Fatal(err)
	}
	abilities, board, err := b.Generate(choice, report)
	if err != nil {
		t.Fatal(err)
	}
	if os.Getenv(defaultBoardEnv) != "" {
		for _, a := range abilities {
			raw, _ := json.MarshalIndent(a, "", "  ")
			header := "# Generated by boardprice.Generate: the custom adventurer's default board\n# (Lean template, standard die, default picks). Regenerate with\n# " + defaultBoardEnv + "=1 go test ./internal/battle/boardprice -run TestDefaultBoardIsGenerated\n"
			if err := os.WriteFile(filepath.Join(contentRoot(), "custom_adventurer_v1", "abilities", a.ID+".yaml"), append([]byte(header), append(raw, '\n')...), 0o644); err != nil {
				t.Fatal(err)
			}
		}
		t.Skip("default board rewritten")
	}
	lib := testCatalog(t)
	for _, a := range abilities {
		shipped, ok := lib.Abilities[a.ID]
		if !ok {
			t.Fatalf("%s is not shipped", a.ID)
		}
		want, _ := json.Marshal(a)
		got, _ := json.Marshal(shipped)
		if string(want) != string(got) {
			t.Fatalf("shipped %s differs from Generate; rerun with %s=1\nshipped:   %s\ngenerated: %s", a.ID, defaultBoardEnv, got, want)
		}
	}
	if combatant := lib.Combatants["custom_adventurer"]; !reflect.DeepEqual(combatant.AbilityBoard, board) || combatant.DiceLoadout[0].DiceID != "standard_d6" {
		t.Fatalf("custom adventurer default board %v on %v; want %v", combatant.AbilityBoard, combatant.DiceLoadout, board)
	}
}

// Every generated ability validates in the catalog and qualifies on its die
// exactly where pricing says its tiers do, with full rules for the hover.
func TestGeneratedAbilitiesValidateAndQualify(t *testing.T) {
	b := testBuilder(t)
	var choices []Choice
	for _, tpl := range b.Menus.Templates {
		for _, entry := range b.Menus.Dice {
			if die, _ := b.Die(entry.ID); die.Layout.Family == tpl.Family {
				choices = append(choices, b.Default(tpl.ID, entry.ID))
			}
		}
	}
	for seed := int64(100); seed < 140; seed++ {
		c, err := b.RandomBoard(rand.New(rand.NewSource(seed)), "")
		if err != nil {
			t.Fatal(err)
		}
		choices = append(choices, c)
	}
	for _, c := range choices {
		resolved, report, err := b.Price(c)
		if err != nil {
			t.Fatalf("%+v: %v", c, err)
		}
		abilities, board, err := b.Generate(resolved, report)
		if err != nil {
			t.Fatal(err)
		}
		die, _ := b.Die(resolved.Die)
		lib := testCatalog(t)
		for _, a := range abilities {
			lib.Abilities[a.ID] = a
		}
		if err := content.ValidateLibrary(lib); err != nil {
			t.Fatalf("%s on %s: generated abilities do not validate: %v", resolved.Template, resolved.Die, err)
		}
		if len(board.Offensive) != len(resolved.Slots) || !reflect.DeepEqual(board.Defensive, resolved.Defenses) {
			t.Fatalf("board %v for %+v", board, resolved)
		}
		loadout := []content.DiceLoadoutEntry{{DiceID: die.ID, Count: 5}}
		for i, a := range abilities {
			if !strings.HasPrefix(a.ID, GeneratedPrefix) || !engine.AbilityFitsDice(a, loadout, lib) {
				t.Fatalf("%s does not qualify on %s", a.ID, die.ID)
			}
			cost, _ := ParseCost(resolved.Slots[i].Cost)
			s := newSolver(die, cost, 5)
			for hand, row := range s.qualify {
				var rolled []state.RolledDie
				for _, f := range s.hands.faces(hand) {
					rolled = append(rolled, state.RolledDie{Face: f, Symbols: []string{die.symbol(f)}})
				}
				tier, ok := engine.QualifiedAbilityTier(a, rolled)
				priced := false
				for _, q := range row {
					priced = priced || q
				}
				if ok != priced {
					t.Fatalf("%s on hand %v: ability qualifies %v, pricing says %v", a.ID, s.hands.faces(hand), ok, priced)
				}
				if ok {
					// The first qualified tier is the most valuable one.
					for _, pt := range report.Tiers {
						if pt.Slot == resolved.Slots[i].Slot && pt.Tier != "" && strings.EqualFold(strings.ReplaceAll(pt.Tier, "+", "_"), tier.ID) {
							for _, other := range report.Tiers {
								if other.Slot == pt.Slot && other.WholeDamage > pt.WholeDamage {
									for j, q := range row {
										if q && cost[j].String() == other.Tier {
											t.Fatalf("%s offers %s before the better %s", a.ID, pt.Tier, other.Tier)
										}
									}
								}
							}
						}
					}
				}
			}
			rules := a.Presentation.RulesText
			for _, pt := range report.Tiers {
				if pt.Slot == resolved.Slots[i].Slot && !strings.Contains(rules, " "+itoa(pt.WholeDamage)+" damage") {
					t.Fatalf("%s rules miss tier %s's damage %d: %s", a.ID, pt.Tier, pt.WholeDamage, rules)
				}
			}
			if !strings.Contains(rules, "Misses") {
				t.Fatalf("%s rules say nothing about a miss: %s", a.ID, rules)
			}
			for _, tier := range cost {
				for _, rc := range tier.Counts {
					if name := b.SymbolName(die, rc.Role); !strings.Contains(rules, name) {
						t.Fatalf("%s rules do not name %s: %s", a.ID, name, rules)
					}
				}
			}
			if rider := resolved.Slots[i].Rider; rider != RiderNone {
				r, _ := b.Menus.Rider(rider)
				if len(r.Operations) > 0 && !strings.Contains(strings.ToLower(rules), riderWord(r)) {
					t.Fatalf("%s rules do not describe rider %s: %s", a.ID, rider, rules)
				}
			}
		}
	}
}

func riderWord(r Rider) string {
	switch r.Operations[0].Type {
	case "apply_status":
		return "protect"
	case "gain_resource":
		return "energy"
	case "draw_cards":
		return "draw"
	}
	return "heal"
}

func itoa(n int) string { raw, _ := json.Marshal(n); return string(raw) }
